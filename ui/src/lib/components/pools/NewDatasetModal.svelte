<script lang="ts">
  import { api, ApiError } from '$lib/api';
  import Button from '$lib/components/Button.svelte';
  import FormField from '$lib/components/FormField.svelte';
  import Modal from '$lib/components/Modal.svelte';

  export let poolName = '';
  export let onClose: () => void;
  export let onCreated: () => void;

  let name = '';
  let compression = 'lz4';
  let quota = '';
  let encrypted = false;
  let saving = false;
  let error = '';

  async function create() {
    saving = true;
    error = '';
    try {
      const options: Record<string, string> = {};
      if (compression) options.compression = compression;
      if (quota.trim()) options.quota = quota.trim();
      if (encrypted) {
        // Raw-key custody (FR-ENC): the API generates the key into a Secret;
        // the browser never handles it.
        options.encryption = 'on';
        options.keyformat = 'raw';
      }
      await api('/api/datasets', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ pool: poolName, name, options })
      });
      onCreated();
    } catch (e) {
      error =
        e instanceof ApiError ? e.message : 'Could not create the dataset. Check the API connection.';
    } finally {
      saving = false;
    }
  }
</script>

<Modal title="New Dataset" {onClose}>
  <p class="text-sm text-gray-400">
    A dataset inside <span class="text-naslos-link">{poolName}</span> becomes a folder you can
    share. Nested names work: <code class="font-mono text-xs">photos/2026</code>.
  </p>

  <form id="new-dataset-form" on:submit|preventDefault={create} class="space-y-4">
    <FormField label="Name" id="pool-field-1" required>
      <input
        id="pool-field-1"
        type="text"
        bind:value={name}
        placeholder="e.g. media"
        class="input w-full"
        required
      />
    </FormField>

    <FormField label="Compression" id="pool-field-2">
      <select id="pool-field-2" bind:value={compression} class="input w-full">
        <option value="lz4">lz4 (fast, good default)</option>
        <option value="zstd">zstd (better ratio, more CPU)</option>
        <option value="off">off</option>
        <option value="gzip">gzip</option>
      </select>
    </FormField>

    <FormField
      label="Quota"
      id="pool-field-3"
      hint="Example: 500G. Leave empty for the pool-wide limit."
    >
      <input
        id="pool-field-3"
        type="text"
        bind:value={quota}
        placeholder="e.g. 500G"
        class="input w-full"
      />
    </FormField>

    <label class="flex cursor-pointer items-start gap-3">
      <input type="checkbox" class="mt-1" bind:checked={encrypted} />
      <span>
        Encrypt this dataset
        <span class="block text-xs text-gray-500">
          The key is generated by the API into a Kubernetes Secret; the browser never sees it. An
          administrator must unlock the dataset after every reboot. Losing the key Secret loses the
          data. Encryption is create-only: existing datasets cannot be converted in place.
        </span>
      </span>
    </label>

    {#if error}
      <div role="alert" class="callout callout-bad mb-0">{error}</div>
    {/if}
  </form>

  <div slot="footer">
    <Button variant="secondary" on:click={onClose}>Cancel</Button>
    <Button
      type="submit"
      form="new-dataset-form"
      loading={saving}
      disabled={!name.trim()}
    >
      Create Dataset
    </Button>
  </div>
</Modal>
